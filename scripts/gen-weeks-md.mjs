// Renders data/weeks/*.json into browsable markdown under progress/month-MM/.
// ponytail: string concat, no template engine. Add one when the layout outgrows this.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "data", "weeks");
const out = join(root, "progress");
const SITE = "https://josa-openlab.github.io/Ti-progress";

const MONTHS = ["January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December"];

const badge = (s) =>
  ({ done: "✅ done", "in-progress": "🟡 in progress", pending: "⬜ pending" })[s] ?? s;

const abs = (u) => (u.startsWith("/") ? SITE + u : u);
const pad = (n) => String(n).padStart(2, "0");

// A week belongs to the calendar month of its deadline.
const monthOf = (w) => w.deadline.slice(0, 7); // "2026-05"
const monthLabel = (key) => `${MONTHS[Number(key.slice(5, 7)) - 1]} ${key.slice(0, 4)}`;
const monthDir = (key) => `month-${key.slice(5, 7)}`;

function renderTask(t) {
  const L = [`### ${t.title}  ${badge(t.status)}`, ""];
  if (t.why) L.push(t.why, "");
  if (t.metrics?.length)
    L.push(
      "| " + t.metrics.map((m) => m.label).join(" | ") + " |",
      "|" + t.metrics.map(() => "---").join("|") + "|",
      "| " + t.metrics.map((m) => m.value).join(" | ") + " |",
      "",
    );
  if (t.reflection) L.push("**What I did**", "", t.reflection, "");
  if (t.commands?.length) L.push("```bash", ...t.commands, "```", "");
  if (t.output) L.push("```", t.output, "```", "");
  if (t.links?.length)
    L.push(...t.links.map((l) => `- [${l.label}](${abs(l.url)})`), "");
  return L.join("\n");
}

function renderWeek(w) {
  const done = w.tasks.filter((t) => t.status === "done").length;
  return [
    `# Week ${pad(w.id)}: ${w.title}`,
    "",
    `${badge(w.status)} · deadline ${w.deadline} · ${done}/${w.tasks.length} tasks`,
    "",
    w.report ? `[Full report on the site](${abs(w.report)})\n` : "",
    `[All weeks](../README.md) · [${monthLabel(monthOf(w))}](README.md)`,
    "",
    "---",
    "",
    ...w.tasks.map(renderTask),
  ].join("\n");
}

const rows = (weeks, prefix = "") => [
  "| Week | Topic | Status | Deadline |",
  "|---|---|---|---|",
  ...weeks.map(
    (w) =>
      `| [${pad(w.id)}](${prefix}week-${pad(w.id)}.md) | ${w.title} | ${badge(w.status)} | ${w.deadline} |`,
  ),
];

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const weeks = readdirSync(src)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(join(src, f), "utf8")))
  .sort((a, b) => a.id - b.id);

const byMonth = new Map();
for (const w of weeks) {
  const k = monthOf(w);
  if (!byMonth.has(k)) byMonth.set(k, []);
  byMonth.get(k).push(w);
}

for (const [key, group] of byMonth) {
  const dir = join(out, monthDir(key));
  mkdirSync(dir, { recursive: true });
  for (const w of group) writeFileSync(join(dir, `week-${pad(w.id)}.md`), renderWeek(w) + "\n");
  writeFileSync(
    join(dir, "README.md"),
    [`# ${monthLabel(key)}`, "", `[All months](../README.md)`, "", ...rows(group), ""].join("\n"),
  );
}

const index = [
  "# Weekly Progress",
  "",
  "One file per week of the JOSA OpenLab apprenticeship, grouped by month.",
  `Same content as the [site](${SITE}), readable straight from the repo.`,
  "",
  ...[...byMonth].flatMap(([key, group]) => [
    `## [${monthLabel(key)}](${monthDir(key)}/)`,
    "",
    ...rows(group, `${monthDir(key)}/`),
    "",
  ]),
  "_Generated by `npm run docs`. Edit `data/weeks/*.json`, not these files._",
].join("\n");

writeFileSync(join(out, "README.md"), index + "\n");
console.log(`wrote ${weeks.length} weeks across ${byMonth.size} months to progress/`);
