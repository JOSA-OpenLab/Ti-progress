// Renders data/weeks/*.json into browsable markdown under MonthN/ at the repo root.
// ponytail: string concat, no template engine. Add one when the layout outgrows this.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "data", "weeks");
const SITE = "https://josa-openlab.github.io/Ti-progress";

const MONTHS = ["January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December"];

const badge = (s) =>
  ({ done: "✅ done", "in-progress": "🟡 in progress", pending: "⬜ pending" })[s] ?? s;

const abs = (u) => (u.startsWith("/") ? SITE + u : u);
const pad = (n) => String(n).padStart(2, "0");

// A week belongs to the calendar month of its deadline; months are then numbered
// in order, so the folders read Month1..MonthN like the program does.
const calKey = (w) => w.deadline.slice(0, 7); // "2026-05"
const calLabel = (k) => `${MONTHS[Number(k.slice(5, 7)) - 1]} ${k.slice(0, 4)}`;

function renderTask(t) {
  const L = [`### ${t.title}  ${badge(t.status)}`, ""];
  if (t.why) L.push(t.why, "");
  if (t.metrics?.length)
    L.push(
      "| " + t.metrics.map((m) => m.label).join(" | ") + " |",
      "|" + t.metrics.map(() => "---").join("|") + "|",
      "| " + t.metrics.map((m) => m.value).join(" | ") + " |",
      "",
    );
  if (t.reflection) L.push("**What I did**", "", t.reflection, "");
  if (t.commands?.length) L.push("```bash", ...t.commands, "```", "");
  if (t.output) L.push("```", t.output, "```", "");
  if (t.links?.length)
    L.push(...t.links.map((l) => `- [${l.label}](${abs(l.url)})`), "");
  return L.join("\n");
}

function renderWeek(w, m) {
  const done = w.tasks.filter((t) => t.status === "done").length;
  return [
    `# Week ${pad(w.id)}: ${w.title}`,
    "",
    `${badge(w.status)} · deadline ${w.deadline} · ${done}/${w.tasks.length} tasks`,
    "",
    w.report ? `[Full report on the site](${abs(w.report)})\n` : "",
    `[All weeks](../PROGRESS.md) · [${m.dir} (${m.label})](README.md)`,
    "",
    "---",
    "",
    ...w.tasks.map(renderTask),
  ].join("\n");
}

const rows = (weeks, prefix = "") => [
  "| Week | Topic | Status | Deadline |",
  "|---|---|---|---|",
  ...weeks.map(
    (w) =>
      `| [${pad(w.id)}](${prefix}week-${pad(w.id)}.md) | ${w.title} | ${badge(w.status)} | ${w.deadline} |`,
  ),
];

const weeks = readdirSync(src)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(join(src, f), "utf8")))
  .sort((a, b) => a.id - b.id);

const grouped = new Map();
for (const w of weeks) {
  const k = calKey(w);
  if (!grouped.has(k)) grouped.set(k, []);
  grouped.get(k).push(w);
}

const months = [...grouped].map(([key, group], i) => ({
  dir: `Month${i + 1}`,
  label: calLabel(key),
  weeks: group,
}));

// Only ever remove folders this script owns.
for (const d of readdirSync(root))
  if (/^Month\d+$/.test(d) && statSync(join(root, d)).isDirectory())
    rmSync(join(root, d), { recursive: true, force: true });

for (const m of months) {
  const dir = join(root, m.dir);
  mkdirSync(dir, { recursive: true });
  for (const w of m.weeks) writeFileSync(join(dir, `week-${pad(w.id)}.md`), renderWeek(w, m) + "\n");
  writeFileSync(
    join(dir, "README.md"),
    [
      `# ${m.dir}: ${m.label}`,
      "",
      "[All months](../PROGRESS.md)",
      "",
      ...rows(m.weeks),
      "",
    ].join("\n"),
  );
}

const index = [
  "# Weekly Progress",
  "",
  "One file per week of the JOSA OpenLab apprenticeship, grouped by month.",
  `Same content as the [site](${SITE}), readable straight from the repo.`,
  "",
  ...months.flatMap((m) => [
    `## [${m.dir}](${m.dir}/) · ${m.label}`,
    "",
    ...rows(m.weeks, `${m.dir}/`),
    "",
  ]),
  "_Generated by `npm run docs`. Edit `data/weeks/*.json`, not these files._",
].join("\n");

writeFileSync(join(root, "PROGRESS.md"), index + "\n");
console.log(`wrote ${weeks.length} weeks across ${months.length} months (${months.map((m) => m.dir).join(", ")})`);
